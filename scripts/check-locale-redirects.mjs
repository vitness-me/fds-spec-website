#!/usr/bin/env node
/**
 * A URL with an explicit /en/ prefix answers with the page it means, not 404.
 *
 * The default locale builds to the site root: /why-fds, /docs/... — there is
 * no /en directory, and by Docusaurus's model there should not be. But the
 * moment a site serves /es/ and /sr-Latn/, symmetric prefixes become what
 * people expect, and /en/... arrives anyway: typed by hand, pasted into chat,
 * rewritten by tools that saw the pattern. GitHub Pages has no server to
 * rewrite it, so the build itself must contain the answer — a client-redirect
 * stub at /en/<path> for every default-locale page, generated by
 * @docusaurus/plugin-client-redirects during the default locale's build.
 *
 * This checks the built output, after `docusaurus build`:
 *
 *   - /en/ resolves and its stub points at /
 *   - /en/why-fds resolves and points at /why-fds (a page outside /docs)
 *   - one real /en/docs/... path resolves and points at its /docs/...
 *     counterpart — the sample is discovered from the build, not listed here
 *   - no translated locale grew an /en of its own (/es/en, /sr-Latn/en would
 *     mean the redirect plugin ran in the wrong locale's build)
 *
 * Locales come from website/i18n/locales.json — the same manifest the config
 * and check-translations.mjs read — so a locale change moves this check with
 * it, with nothing to edit here.
 *
 *   node scripts/check-locale-redirects.mjs
 */

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = join(ROOT, 'website/build');
const { defaultLocale, locales } = JSON.parse(
  readFileSync(join(ROOT, 'website/i18n/locales.json'), 'utf8'),
);

const problems = [];

if (!existsSync(BUILD)) {
  console.error('website/build does not exist — run the website build first; this check reads its output.');
  process.exit(1);
}

/** The redirect stub at build/<prefixed path>, asserted to point at target. */
function checkStub(stubRel, target) {
  const candidates = [join(BUILD, stubRel, 'index.html'), join(BUILD, `${stubRel}.html`)];
  const stub = candidates.find((c) => existsSync(c));
  if (!stub) {
    problems.push(
      `/${stubRel} does not resolve in the built site — a reader who types the /${defaultLocale}/ prefix gets a 404. ` +
        `The client-redirects plugin should emit a stub here during the default locale's build.`,
    );
    return;
  }
  const html = readFileSync(stub, 'utf8');
  if (!html.includes(`url=${target}`) && !html.includes(`href="${target}"`)) {
    problems.push(`${relative(ROOT, stub)}: exists but does not point at ${target} — the stub redirects somewhere else.`);
  }
}

// A real docs page, discovered from the build rather than hand-picked.
function firstDocsPage() {
  const queue = [join(BUILD, 'docs')];
  while (queue.length > 0) {
    const dir = queue.shift();
    if (!existsSync(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) queue.push(full);
      else if (entry.name.endsWith('.html')) return relative(BUILD, full).split(sep).join('/').replace(/\.html$/, '');
    }
  }
  return null;
}

checkStub(defaultLocale, '/');
checkStub(`${defaultLocale}/why-fds`, '/why-fds');

const docsPage = firstDocsPage();
if (docsPage === null) {
  problems.push('the build has no docs pages at all — nothing to sample; that is its own problem.');
} else {
  checkStub(`${defaultLocale}/${docsPage}`, `/${docsPage}`);
}

// The redirect tree belongs to the default locale's build only.
for (const locale of locales) {
  if (locale === defaultLocale) continue;
  if (existsSync(join(BUILD, locale, defaultLocale))) {
    problems.push(
      `website/build/${locale}/${defaultLocale} exists — the redirect plugin ran inside the ${locale} build; ` +
        `it must be limited to the default locale's build in docusaurus.config.ts.`,
    );
  }
}

if (problems.length > 0) {
  console.error(`${problems.length} locale-redirect problem(s):\n`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}
console.log(`/${defaultLocale}/* answers with the page it means: root, /why-fds and /${docsPage} all covered.`);
